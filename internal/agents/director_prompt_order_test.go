package agents

// 这条用例固化 run() 里 system prompt 的**拼装顺序**：稳定 → 易变。
//
// 前缀缓存按段失效：最易变的段是 customAgentPromptSection（注册/加载一个 plasma Agent
// 就变），它必须排在末尾 —— 一旦挪回 blueprint / skills / mcp 之前，那三段的前缀缓存会被
// 它的抖动一并作废，症状只是"慢"，没有任何崩溃能提醒你顺序错了。
//
// 只断言**相对位置**，不断言文案：文案各有自己的用例（director_test.go 的
// TestSystemPrompt_WithCustomAgents、injection_test.go 的两条注入用例）。

import (
	"context"
	"strings"
	"testing"

	"yagent/internal/config"
	"yagent/internal/memory"
)

// customAgentsTail 是 customAgentPromptSection 的最后一句 WriteString
// （director_surface.go）。末尾性断言只认它：抬头能命中"这一段在"，命不中"它之后没别的"。
const customAgentsTail = "Use these agents via their delegate tools for tasks matching their specializations."

func TestDirectorSystemPromptSectionsOrderedStableToVolatile(t *testing.T) {
	t.Cleanup(func() {
		config.SetGlobalSkills(config.DefaultSkillsConfig(), config.SkillsPresence{})
		config.SetGlobalMCP(config.DefaultMCPConfig(), config.MCPPresence{})
	})

	// 四段全部打开，否则"顺序"里少一段就等于少断言一条边（夹具小到没触发分支）。
	skillsCfg := config.DefaultSkillsConfig()
	skillsCfg.InjectInto = []string{"director"}
	config.SetGlobalSkills(skillsCfg, config.SkillsPresence{Section: true, Enable: true, InjectInto: true})

	mcpCfg := config.DefaultMCPConfig()
	mcpCfg.StatusLine = true
	config.SetGlobalMCP(mcpCfg, config.MCPPresence{Section: true, Enable: true, StatusLine: true})

	workDir, snap := blueprintProject(t)
	engine := newScripted(map[string][]scriptStep{"director": {fixed(textResponse("完成"))}})
	d := newDirectorAgentForTest(newTestGlobalCtx(workDir), engine,
		nil, nil, nil, nil, nil, nil, 10, nil, 3, config.Config{}, nil)
	d.blueprint = NewBlueprintView(&testBlueprintSource{root: workDir, snap: snap},
		"director", true, 4000, 1500, nil)
	d.external.Skills = &fakeSkillSource{catalog: "## Skills\n- demo: 演示技能"}
	d.external.Status = func() string { return "alpha: ready — 3 tools" }
	d.registerCustomAgent(&CustomAgent{
		Name: "order_probe", DisplayName: "Order Probe",
		SystemPrompt: "probe", Description: "顺序探针",
	})

	ctx := memory.WithConversationMemory(context.Background(), memory.NewConversationMemory(300))
	if _, err := d.Run(ctx, "随便看看"); err != nil {
		t.Fatalf("Director.Run: %v", err)
	}
	sys := lastCallFor(t, engine, "director").Messages[0].Content

	// 稳定 → 易变。工具目录取自 Surface 本身（不写死抬头文案），其余各段取**带正文的完整抬头**。
	//
	// 标记必须唯一到段：光写 "# Repository Blueprint" 会命中 director.prompt.md 里提到这个
	// 名字的那一句（模板里第一次出现的位置远在 blueprint 块之前），于是断言自己造出一个假位置。
	order := []struct{ site, marker string }{
		{"工具目录", firstNonEmptyLine(d.surface.Catalog())},
		{"blueprint", blueprintBlockTitle},
		{"skills", "## Skills\n- demo: 演示技能"},
		{"mcp", "## MCP servers\nalpha: ready — 3 tools"},
		{"custom agents", "### Custom Agents\nThese agents were generated by plasma"},
	}
	prev, prevSite := -1, ""
	for _, s := range order {
		if s.marker == "" {
			t.Fatalf("%s 段的标记为空：夹具没渲染出这一段，顺序断言会退化成证明空气", s.site)
		}
		at := strings.Index(sys, s.marker)
		if at < 0 {
			t.Fatalf("%s 段没进 system prompt：\n%s", s.site, truncateForFailure(sys))
		}
		if at <= prev {
			t.Errorf("%s 段位置 = %d，必须在 %s 段（%d）之后；拼接顺序是 稳定 → 易变",
				s.site, at, prevSite, prev)
		}
		prev, prevSite = at, s.site
	}

	// 最易变段只能出现一次、且确实在末尾（它之后不再有任何段）：次数由下一条计数断言守，
	// 末尾性由再下一条尾句断言守——两条缺一，剩下的那条都会误报为绿。
	if n := strings.Count(sys, "### Custom Agents\nThese agents were generated by plasma"); n != 1 {
		t.Errorf("custom agents 段出现了 %d 次，要 1 次", n)
	}

	// 上面那条「只能是 1 次」证明的是**它出现过**，不是**它之后没内容**：有人往拼接链末尾
	// 再追加一段时，抬头位置照旧命中、次数照旧是 1，最易变段就被静默挤回中间，前缀缓存
	// 重新被它的抖动作废，症状只剩"慢"。末尾性只能靠**尾句**判定——尾句是该段最后一句
	// WriteString（director_surface.go 的 customAgentPromptSection），它之前必有本段正文，
	// 之后必须什么都没有。
	at := strings.Index(sys, customAgentsTail)
	if at < 0 {
		t.Fatalf("custom agents 段的尾句没进 system prompt（夹具失效）：\n%s", truncateForFailure(sys))
	}
	if rest := sys[at+len(customAgentsTail):]; strings.TrimSpace(rest) != "" {
		t.Errorf("最易变段必须在 system prompt 末尾，其后不得再有任何段落：尾句之后还剩 %d 字节：%s",
			len(rest), truncateForFailure(rest))
	}
}

// firstNonEmptyLine 取第一行非空内容：Catalog() 以换行开头，Split("\n")[0] 会得到空串，
// 而空串在 strings.Index 里命中 0 —— 那是一条永远不会失败的断言。
func firstNonEmptyLine(s string) string {
	for _, line := range strings.Split(s, "\n") {
		if strings.TrimSpace(line) != "" {
			return line
		}
	}
	return ""
}
